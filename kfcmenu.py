"""### 5. Food & Drink Search, Recommendation, and Opinion System"""

import difflib

def search_and_recommend(user_query, df_menu, model, scaler, le_target, feature_cols):
    """
    Searches for a food/drink in the menu.
    If found, gives its details, ingredients, and an opinion using the model.
    If not found, suggests the most similar item available with ingredients.
    """
    products = df_menu['Products'].dropna().unique().tolist()

    # Find close matches
    matches = difflib.get_close_matches(user_query, products, n=1, cutoff=0.5)

    if matches and matches[0].lower() == user_query.lower():
        matched_item = matches[0]
        print(f"✓ Great news! '{matched_item}' is available in our menu.\n")
        provide_opinion(matched_item, df_menu, model, scaler, le_target, feature_cols)
    else:
        print(f"✗ Sorry, your searched item '{user_query}' is not directly available in our menu.")
        if matches:
            similar_item = matches[0]
            print(f"💡 However, we found a very similar item for you: '{similar_item}'")
            print("📖 Suggestion: You can order this or try its recipe/style as a substitute!\n")
            provide_opinion(similar_item, df_menu, model, scaler, le_target, feature_cols)
        else:
            # Default fallback if no close match is found at all
            fallback_item = products[0]
            print(f"💡 We couldn't find an exact match. You might like our popular option: '{fallback_item}'\n")
            provide_opinion(fallback_item, df_menu, model, scaler, le_target, feature_cols)

def provide_opinion(item_name, df_menu, model, scaler, le_target, feature_cols):
    # Extract row
    row = df_menu[df_menu['Products'] == item_name].iloc[0]

    # Get basic details
    energy = row.get('Total Energy', 'Unknown')
    sugar = row.get('Su gar', 'Unknown')
    fat = row.get('Tot al Fat', 'Unknown')
    allergens = row.get('Allergens', 'Unknown')

    # Use our trained RandomForest classifier to predict energy class dynamically
    item_encoded = X_adv[df_advanced['Products'] == item_name].iloc[0:1]

    if not item_encoded.empty:
        item_scaled = item_encoded.copy()
        non_dummy = [col for col in numeric_candidates if col in item_encoded.columns]
        item_scaled[non_dummy] = scaler.transform(item_encoded[non_dummy])

        # Predict class
        pred_code = model.predict(item_scaled)[0]
        pred_label = le_target.inverse_transform([pred_code])[0]
    else:
        pred_label = "Unknown"

    print(f"--- AI Opinion, Ingredients & Nutrition Profile for '{item_name}' ---")
    print(f"• Energy Content: {energy} kcal")
    print(f"• Sugar: {sugar}g | Total Fat: {fat}g")
    print(f"• Ingredients / Allergen Info: {allergens}")
    print(f"• AI Diet Analysis: This is classified as a *{pred_label} Energy* choice.")

    # AI Opinion Feedback
    if pred_label == 'High':
        print("💬 Opinion: This is a rich, high-energy option. Perfect for active days or post-workout fuel, but enjoy in moderation!")
    else:
        print("💬 Opinion: This is a lighter, low-energy option. Great for a healthy, guilt-free snack!")
    print("-" * 50)

