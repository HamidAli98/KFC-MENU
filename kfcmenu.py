# Any column not explicitly categorical and not target-related is a candidate for numerical parsing
numeric_candidates = [col for col in df_advanced.columns if col not in categorical_cols + ['Total Energy', 'Energy_Class']]

# Clean and convert the numerical candidates
for col in numeric_candidates:
    # Clean strings (remove spaces, units, non-numeric chars) and convert to float
    df_advanced[col] = pd.to_numeric(df_advanced[col].astype(str).str.replace(r'[^\d.]', '', regex=True), errors='coerce')
    # Impute missing numerical values with column median
    df_advanced[col] = df_advanced[col].fillna(df_advanced[col].median())

# Re-create Target based on 'Total Energy'
df_advanced['Total Energy'] = pd.to_numeric(df_advanced['Total Energy'].astype(str).str.replace(r'[^\d.]', '', regex=True), errors='coerce')
median_energy = df_advanced['Total Energy'].median()
df_advanced['Energy_Class'] = np.where(df_advanced['Total Energy'] >= median_energy, 'High', 'Low')

# Define X and y
X_adv = df_advanced.drop(columns=['Energy_Class', 'Total Energy'])
y_adv = df_advanced['Energy_Class']

# Handle missing values for categorical features before one-hot encoding
for col in categorical_cols:
    if col in X_adv.columns:
        X_adv[col] = X_adv[col].fillna('Unknown')

# Encode target
le_target_adv = LabelEncoder()
y_encoded_adv = le_target_adv.fit_transform(y_adv)

# Encode remaining categorical features using One-Hot Encoding
existing_cat_cols = [col for col in categorical_cols if col in X_adv.columns]
